import { expect, test } from '@playwright/test';
test('captura redesign', async ({ page }) => {
  const p = test.info().project.name;
  await page.goto('/carga-1');
  await expect(page.getByRole('heading', { name: 'O que você vai fazer?' })).toBeVisible();
  await page.screenshot({ path: `test-results/novo-publica-${p}.png`, fullPage: true });
  await page.getByRole('button', { name: /^Escolher Corte masculino/ }).click();
  await page.getByRole('button', { name: /^Escolher Barba/ }).click();
  const prof = page.locator('.pub-profissional').first();
  if (await prof.count()) await prof.click();
  await page.locator('.pub-dia').nth(2).click();
  await page.locator('.pub-horario:not([disabled])').nth(3).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: `test-results/novo-publica-horario-${p}.png`, fullPage: true });
  await page.goto('/login');
  await page.screenshot({ path: `test-results/novo-login-${p}.png` });
  await page.getByLabel(/usu[aá]rio/i).fill('dono_carga_1');
  await page.getByLabel(/senha/i).fill('Carga-123!');
  await page.getByRole('button', { name: /entrar/i }).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.getByRole('button', { name: 'Todos', exact: true }).click();
  await expect(page.locator('.agendamento-card').first()).toBeVisible();
  await page.screenshot({ path: `test-results/novo-painel-${p}.png` });
});
